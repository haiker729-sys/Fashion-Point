function buildVariants(
  baseSku: string,
  combos: Array<{ colour: string; hex: string; sizes: Record<string, number> }>
): ProductVariant[] {
  const result: ProductVariant[] = [];
  for (const combo of combos) {
    const colorCode = combo.colour
      .replace(/[^A-Za-z]/g, '')
      .slice(0, 3)
      .toUpperCase();
    for (const [size, stockQuantity] of Object.entries(combo.sizes)) {
      result.push({
        id: `${baseSku}-${colorCode}-${size}`.toLowerCase().replace(/[^a-z0-9-]/g, ''),
        colour: combo.colour,
        colourHex: combo.hex,
        size,
        sku: `${baseSku}-${colorCode}-${size.replace(/\s+/g, '')}`.toUpperCase(),
        stockQuantity,
      });
    }
  }
  return result;
}

